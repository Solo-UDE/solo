export function buildDesignKitUserPrompt(userRequest: string, references?: string): string {
  let prompt = `Create a comprehensive design kit for the following request:\n\n${userRequest}`;
  if (references) {
    prompt += `\n\n<references>\n${references}\n</references>`;
  }
  return prompt;
}

export function buildDesignKitEditorUserPrompt(
  existingKit: string,
  newReferences: string,
  userRequest: string
): string {
  return `<existing_design_kit>\n${existingKit}\n</existing_design_kit>\n\n<new_references>\n${newReferences}\n</new_references>\n\n<user_request>\n${userRequest}\n</user_request>`;
}
